package variables;

public class variables {
    public static void main(String[] args) {

        int num1 = 10;
        int num2 = 20;
        int result = num1 + num2;
        System.out.println("The sum of num1 and num2 is: " + result);
    }
}

/* Variables: Variables are fundamental to programming as they allow us to store and manipulate data in our programs.
    1. A variable is a container for storing data values. 
    2. In Java, each variable must be declared with a specific data type, which determines the kind of data it can hold. 
    3. A variable can be declared and initialized in a single line or in separate lines.
    4. And the value of a variable can be changed during the program execution, which is why they are called "variables".
    5. Also variables must be declared before they can be used, and they must have a unique name within their scope.
    6. Finally, Java is a statically-typed language, which means that the data type of a variable must be specified at the time of 
       declaration and cannot be changed later.
    7. Variables can be of different types, such as int, float, char, boolean, and String, among others. 
    8. And each type of variable can hold different kinds of data. 
    For example, an int variable can hold whole numbers, while a String variable can hold text.

     The syntax for declaring a variable is: 
        Syntax: DataType variableName = value;
        Example: int myNum = 5; // This declares an integer variable named myNum and assigns it the value 5.
*/


